/**
 * Generates `src/workspace-glyphs.ts`: the inline SVG of each workspace icon glyph, copied from the studio's product
 * icon artwork, so server-rendered pages draw a picked glyph from the shipped set. Run: `node scripts/generate-glyphs.ts`.
 * `tests/workspace-glyphs.spec.ts` fails when the committed file differs from this script's output.
 */
import { writeFileSync } from 'node:fs'
import { ICON_ARTWORK, ICON_MEDIUM_STROKE } from '../../../../packages/client/ui-primitives/src/icons/artwork.ts'

/** Each workspace glyph and the product icon artwork it draws. */
const ARTWORK_OF = {
  folder: 'folder-close',
  code: 'code-outline',
  database: 'database-outline',
  globe: 'globe-outline',
  branch: 'branch-outline',
  shield: 'shield-outline',
  sparkle: 'sparkle',
  think: 'think-outline',
  goal: 'goal-outline',
  gauge: 'gauge-outline',
  api: 'api-outline',
  browse: 'browse-outline',
  data: 'data-outline',
  document: 'deliver-doc',
  plan: 'plan-outline',
  checklist: 'checklist-outline',
  skill: 'skill-outline',
  plugin: 'cordis-plugin-outline',
  pinwheel: 'plugin-pinwheel-outline',
  person: 'personalization-outline',
  users: 'users-outline',
  user: 'user-outline',
  microphone: 'microphone-outline',
  send: 'send-outline',
  link: 'link-outline',
  sun: 'light-outline',
  moon: 'dark-outline',
  clock: 'clock-outline',
  queue: 'queue-outline',
  inspect: 'inspect-outline',
  settings: 'settings-outline',
  enhance: 'enhance-outline',
  tree: 'workspace-tree-outline',
  pin: 'pin-outline',
  archive: 'archive-outline',
  save: 'save-outline',
} as const

/**
 * The generated module's text.
 * @returns the TypeScript source.
 */
export function generate(): string {
  const entries = Object.entries(ARTWORK_OF).map(([glyph, key]) => {
    const artwork = ICON_ARTWORK[key as keyof typeof ICON_ARTWORK]
    return `  ${glyph}: ${JSON.stringify(artwork.svg(ICON_MEDIUM_STROKE))},`
  })
  return `/**
 * The inline SVG of each workspace icon glyph, in the current text colour. Generated by \`scripts/generate-glyphs.ts\`;
 * do not edit.
 * @module @delorun/brand/workspace-glyphs
 */
import type { IconGlyph } from './workspace-icon.ts'

/** The SVG document of each glyph, drawn with \`currentColor\`. */
export const GLYPH_SVG: Readonly<Record<IconGlyph, string>> = {
${entries.join('\n')}
}
`
}

if (process.argv[1] !== undefined && import.meta.url === new URL(process.argv[1], 'file:').href) writeFileSync(new URL('../src/workspace-glyphs.ts', import.meta.url), generate())

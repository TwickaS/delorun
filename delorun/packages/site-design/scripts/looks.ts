/**
 * Builds the looks stylesheet: for each theme of the studio's Theme plugin, in light and dark, the colour roles the brand
 * tokens read, resolved to literal colours. The generator is the plugin's own, so a site can never differ from the studio.
 * Run `node scripts/write-looks.ts` in this package after the plugin's palettes change; `tests/looks.spec.ts` fails while
 * `src/looks.css` is out of date.
 *
 * @module @delorun/site-design/scripts/looks
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DEFAULT_SETTINGS, DENSITY_SCALE, PRESET_PALETTES, type ThemeSettings } from '../../plugin-theme/src/config.ts'
import { contrast, formatRgb, type Rgb } from '../../plugin-theme/src/palette/color.ts'
import { applyLayers, requireResolved, type SchemeValues } from '../../plugin-theme/src/palette/generate.ts'
import { themeLayers } from '../../plugin-theme/src/palette/layers.ts'
import { ACCENT_IDS } from '../../plugin-theme/src/palette/soft.ts'
import { STOCK_TOKENS } from '../../plugin-theme/src/palette/stock.ts'

/** The studio roles the brand tokens read, by the name the stylesheet gives each. */
export const ROLES = {
  accent: '--dsw-alias-brand-primary',
  'accent-text': '--dsw-alias-link',
  'on-accent': '--dsw-alias-label-primary-foreground',
  text: '--dsw-alias-label-primary',
  muted: '--dsw-alias-label-secondary',
  surface: '--dsw-alias-bg-base',
  raised: '--dsw-alias-bg-layer-1',
  sunken: '--dsw-alias-bg-layer-2',
  border: '--dsw-alias-border-l2',
  info: '--dsw-alias-state-business-primary',
  success: '--dsw-alias-state-success-primary',
  warning: '--dsw-alias-state-warn-primary',
  error: '--dsw-alias-state-error-primary',
} as const

/** A role's name in the stylesheet. */
export type RoleName = keyof typeof ROLES

/** One look: a preset palette, or the custom palette with one accent preset. */
export interface Look {
  /** The palette id, as the studio stores it. */
  readonly palette: ThemeSettings['palette']
  /** The accent preset when the palette is `custom`. */
  readonly accent?: (typeof ACCENT_IDS)[number]
}

/** Every look the stylesheet carries, in the order the control lists them. */
export const LOOKS: readonly Look[] = [
  ...PRESET_PALETTES.map((palette): Look => ({ palette })),
  ...ACCENT_IDS.map((accent): Look => ({ palette: 'custom', accent })),
]

/** The roles of one look in one scheme as literal colours. */
export type LookColours = Readonly<Record<RoleName, Rgb>>

/**
 * Resolves a look's roles.
 * @param look - the look.
 * @param scheme - the colour scheme.
 * @returns each role as a colour.
 */
export function resolveLook(look: Look, scheme: 'light' | 'dark'): LookColours {
  const settings: ThemeSettings = { ...DEFAULT_SETTINGS, studioAdditions: true, palette: look.palette, ...look.accent === undefined ? {} : { accent: look.accent } }
  const layers = themeLayers(settings)
  const values: SchemeValues = applyLayers(STOCK_TOKENS, [layers.palette ?? {}, layers.accent ?? {}], scheme)
  return Object.fromEntries(Object.entries(ROLES).map(([name, role]) => [name, requireResolved(values, role)])) as LookColours
}

/**
 * The WCAG contrast of two roles of a look.
 * @param colours - the look's colours.
 * @param foreground - the text role.
 * @param background - the surface role; an opaque colour.
 * @returns the ratio.
 */
export function ratio(colours: LookColours, foreground: RoleName, background: RoleName): number {
  return contrast(colours[foreground], colours[background])
}

/** The value of `--look-contrast` for each stop: both stops move quiet text and rules towards the text colour. The palettes put quiet text at the AA floor, so no stop weakens it. */
export const CONTRAST_STOPS = { high: 0.25, highest: 0.5 } as const

/** The attribute selector of a look. */
export function selector(look: Look): string {
  return look.accent === undefined ? `[data-look="${look.palette}"]` : `[data-look="custom"][data-accent="${look.accent}"]`
}

/**
 * The T3 Code notice the stylesheet keeps.
 * @returns the comment.
 */
function notice(): string {
  const text = readFileSync(fileURLToPath(new URL('../../plugin-theme/THIRD_PARTY_NOTICES.md', import.meta.url)), 'utf8')
  const commit = /commit `([0-9a-f]{40})`/.exec(text)?.[1]
  const holder = /^Copyright \(c\) .*$/m.exec(text)?.[0]
  if (commit === undefined || holder === undefined) throw new Error('THIRD_PARTY_NOTICES.md no longer names the T3 Code commit and copyright line')
  return `/*\n * The Slate, Berry, Grove, Ocean, Ember and Iris looks derive from the themes of T3 Code (MIT licence), commit ${commit}.\n * ${holder}\n * The licence text is at /notices. Generated by packages/site-design/scripts/looks.ts; do not edit.\n */`
}

/**
 * The stylesheet.
 * @returns the CSS text.
 */
export function buildLooks(): string {
  const rules = LOOKS.map(look => {
    const light = resolveLook(look, 'light')
    const dark = resolveLook(look, 'dark')
    const lines = (Object.keys(ROLES) as RoleName[]).map(name => `  --look-${name}: light-dark(${formatRgb(light[name])}, ${formatRgb(dark[name])});`)
    return `${selector(look)} {\n${lines.join('\n')}\n}`
  })
  const stops = Object.entries(CONTRAST_STOPS).map(([name, value]) => `[data-contrast="${name}"] { --look-contrast: ${value}; }`)
  const density = Object.entries(DENSITY_SCALE).map(([name, scale]) => `[data-density="${name}"] { --dsh-density: ${scale}; }`)
  return `${notice()}\n\n${rules.join('\n\n')}\n\n${GENERIC}\n${stops.join('\n')}\n${density.join('\n')}\n`
}

/**
 * Maps a look's roles onto the studio roles the brand tokens read. Contrast is one number on the root,
 * `--look-contrast` from 0 to 1: quiet text and rules move up to 60% towards the text colour.
 */
const GENERIC = `[data-look] {
  --dsw-alias-brand-primary: var(--look-accent);
  --dsw-alias-brand-text: var(--look-accent-text);
  --dl-on-accent: var(--look-on-accent);
  --dsw-alias-label-primary: var(--look-text);
  --dsw-alias-bg-base: var(--look-surface);
  --dsw-alias-bg-layer-1: var(--look-raised);
  --dsw-alias-bg-layer-2: var(--look-sunken);
  --dsw-alias-state-business-primary: var(--look-info);
  --dsw-alias-state-success-primary: var(--look-success);
  --dsw-alias-state-warn-primary: var(--look-warning);
  --dsw-alias-state-error-primary: var(--look-error);
  --dsw-alias-label-secondary: color-mix(in srgb, var(--look-text) calc(var(--look-contrast, 0) * 60%), var(--look-muted));
  --dsw-alias-border-l2: color-mix(in srgb, var(--look-text) calc(var(--look-contrast, 0) * 60%), var(--look-border));
}
`

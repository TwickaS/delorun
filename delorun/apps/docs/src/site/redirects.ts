/**
 * The redirects from the addresses pages had before they moved into group folders. One list of moved pages is the
 * source: the build writes it as the host's `_redirects` file, and the specs check that each target is a published page.
 *
 * @module @delorun/docs/redirects
 */
import { prefixOf, type Locale } from './locale.ts'
import { type Section } from './routes.ts'

/** A page that moved into a group folder. */
export interface MovedPage {
  /** The section the page belongs to. */
  readonly section: Section
  /** The page's slugs before the move, such as `install`. */
  readonly from: string
  /** The page's slugs now, such as `get-started/install`. */
  readonly to: string
  /** Whether the page is a directory's index page (`README`), whose Markdown route ends in `index`. */
  readonly index?: boolean
}

/**
 * The guide's group folders, each with its pages in reading order. The folder names are the first slug of each page's
 * new address; the groups' titles are in each folder's `meta.json`.
 */
const GUIDE_GROUPS: Readonly<Record<string, readonly string[]>> = {
  'get-started': ['install', 'providers', 'switching', 'import-deepseek-chats'],
  'everyday-use': ['daily-use', 'cost-meter', 'thinking-tab', 'use-your-own-browser', 'reach', 'agents'],
  'safety-and-updates': ['safety', 'trust', 'prompt-injection', 'updates'],
  help: ['troubleshooting', 'known-issues', 'logs', 'questions'],
  customising: ['customise', 'changing-your-harness', 'home', 'move-your-setup'],
  'plugin-guides': ['first-plugin', 'plugins', 'updating-with-plugins'],
}

/** The reference folder that holds the parity pages. */
const PARITY_FOLDER = 'parity-with-deepseek-harness'

/** Every page that moved, in the order of the sidebar. */
export const MOVED_PAGES: readonly MovedPage[] = [
  ...Object.entries(GUIDE_GROUPS).flatMap(([folder, pages]) => pages.map((page): MovedPage => ({ section: 'guide', from: page, to: `${folder}/${page}` }))),
  { section: 'reference', from: 'parity', to: `${PARITY_FOLDER}/parity` },
  { section: 'reference', from: 'parity-baseline', to: `${PARITY_FOLDER}/parity-baseline` },
  { section: 'reference', from: 'divergence', to: `${PARITY_FOLDER}/divergence`, index: true },
]

/** A redirect: the old address and the new one. */
export interface Redirect {
  readonly from: string
  readonly to: string
}

/**
 * The old and new addresses of one moved page in one locale: its HTML route and its Markdown route.
 * @param page - the moved page.
 * @param locale - the locale.
 * @returns the two redirects.
 */
function redirectsOf(page: MovedPage, locale: Locale): Redirect[] {
  const prefix = prefixOf(locale)
  const markdown = (slugs: string) => `${prefix}/llms.mdx/${page.section}/${slugs}${page.index === true ? '/index' : ''}`
  return [
    { from: `${prefix}/${page.section}/${page.from}`, to: `${prefix}/${page.section}/${page.to}` },
    { from: markdown(page.from), to: markdown(page.to) },
  ]
}

/**
 * Every redirect of the moved pages: the HTML and Markdown routes in both locales.
 * @returns the redirects, grouped by page.
 */
export function allRedirects(): Redirect[] {
  return MOVED_PAGES.flatMap(page => (['en', 'zh'] satisfies Locale[]).flatMap(locale => redirectsOf(page, locale)))
}

/**
 * The host's `_redirects` file: one permanent redirect per line.
 * @returns the file's text, ending with one newline.
 */
export function redirectsFile(): string {
  const lines = allRedirects().map(({ from, to }) => `${from} ${to} 301`)
  return `# Generated by the build from src/site/redirects.ts: the addresses pages had before they moved into groups.\n${lines.join('\n')}\n`
}

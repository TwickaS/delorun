/**
 * Measures each screenshot's colour once and writes `src/home/shot-colours.ts`, which the home page's mosaic
 * reads to place tiles by brightness and hue, from each picture's L2 file in `public/lod/`. Run it after
 * `lod.ts tiles`.
 *
 * Usage: `node scripts/shot-colours.ts`
 *
 * @module @delorun/website/scripts/shot-colours
 */
import { writeFileSync } from 'node:fs'
import { LOD_TILES } from '../src/home/lod-tiles.ts'
import { SHOTS } from '../src/home/shots.ts'
import { measure } from './colour.ts'

const rows: string[] = []
for (const shot of SHOTS) {
  const file = new URL(`../public/lod/${shot.id}.2.${LOD_TILES[shot.id]?.[1] ?? ''}.webp`, import.meta.url).pathname
  const { l, a, b: bb, hex, peach } = measure(file, shot.device === 'phone')
  rows.push(`  '${shot.id}': { l: ${l.toFixed(1)}, a: ${a.toFixed(1)}, b: ${bb.toFixed(1)}, hex: '${hex}', peach: ${peach.toFixed(4)} },`)
}

writeFileSync(new URL('../src/home/shot-colours.ts', import.meta.url), `/**
 * Each screenshot's colour, as a 16:10 tile shows it: the mean colour in CIE Lab (lightness 0 to 100) and as
 * an sRGB hex (a tile's colour until its picture loads), and the share of its pixels in the peach family. Generated by \`scripts/shot-colours.ts\`; do not edit by hand.
 *
 * @module @delorun/website/home/shot-colours
 */

/** One picture's measured colour. */
export interface ShotColour { readonly l: number; readonly a: number; readonly b: number; readonly hex: string; readonly peach: number }

/** The colours, by picture id. */
export const SHOT_COLOURS: Readonly<Record<string, ShotColour>> = {
${rows.join('\n')}
}
`)
console.log(`measured ${rows.length} pictures`)

/**
 * The replica's studio facade generator. The website's TypeScript program cannot check the real studio components'
 * sources: their props come from declaration-merged slot types that need the studio's own type context. This module
 * reads each component in `studio/components.ts` with the component package's own compiler options and writes
 * `studio/facade.d.ts`, where every component's props are self-contained types the website can check. A change to a
 * component's props then fails the website's type check where the replica passes them.
 *
 * Run `node_modules/.bin/tsx delorun/apps/website/src/replica/build/facade.ts` to write the file, and add `--check`
 * to exit 1 when the file is out of date.
 * @module @delorun/website/replica/build/facade
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import ts from 'typescript'
import { STUDIO_COMPONENTS, type StudioComponent } from '../studio/components.ts'

/** The facade's location, relative to the repository's root. */
const FACADE_FILE = 'delorun/apps/website/src/replica/studio/facade.d.ts'

/** The header of the generated file. */
const HEADER = '// Generated by build/facade.ts from the components\' own exported types; do not edit. Run it after a component\'s props change.'

/** The files of Delorun's packages that the website can import as pure type modules. */
const IMPORTABLE_FILES = /(?:\/wire\.ts|\/versions-api\.ts|\/host-api\.ts)$/u

/** The diagnostics that mean a component's imports did not resolve, which would turn its props into `any`. */
const UNRESOLVED_CODES = new Set([2304, 2307, 2552, 2792])

/** The `ts` members the generator reads that the public declarations leave out. */
type TsInternals = typeof ts & { getCheckFlags?: (symbol: ts.Symbol) => number }

/**
 * Named types printed as `unknown`. A session reference reaches the agent's Cordis context, whose members run to
 * thousands of declarations; the replica only passes it through a provider it implements itself.
 */
const OPAQUE_TYPES = new Set(['SessionReference'])

/** The length under which a type used more than once is written out where it is used instead of declared. */
const SHARED_MIN_LENGTH = 80

/** The number of lines from which a type is declared once, so that the same type reached from several components is not written out again. */
const DECLARED_MIN_LINES = 6

/** The deepest nesting of types the printer follows; a props type nested deeper is a printer failure, not a type to cut. */
const MAX_DEPTH = 40

/** The name the checker gives the property keyed by the brand package's unique symbol. */
const BRAND_KEY = /^__@BRAND@\d+$/u

/** The checker flag of a read-only transient property. */
const CHECK_FLAG_READONLY = 8

/** The `ts.TupleType.elementFlags` values. */
const ELEMENT_OPTIONAL = 2
const ELEMENT_REST = 4
const ELEMENT_VARIADIC = 8

/** What the printer carries while it walks one props type. */
interface PrintContext {
  readonly checker: ts.TypeChecker
  readonly root: string
  readonly component: StudioComponent
  /** The types being printed, from the props type down to the current one. */
  readonly path: ts.Type[]
  readonly warnings: string[]
  /** Whether this pass only counts how many times each type is reached. */
  readonly counting: boolean
  /** How many times each type is reached, from the counting pass. */
  readonly counts: Map<ts.Type, number>
  /** The names of the types the facade declares once and the printer refers to by name. */
  readonly names: Map<ts.Type, string>
  /** The declared bodies of those types, by name. */
  readonly lifted: Map<string, string>
}

/** A compiler program with the options of one package tsconfig. */
interface Compiled {
  readonly program: ts.Program
  readonly checker: ts.TypeChecker
}

/**
 * A component's file as an absolute path.
 * @param root - the repository's root.
 * @param file - the component's file as written in `STUDIO_COMPONENTS`.
 * @returns the absolute path.
 */
function sourcePath(root: string, file: string): string {
  return file.startsWith('#studio/') ? join(root, 'packages/client', file.slice('#studio/'.length)) : join(root, file)
}

/**
 * Parse a tsconfig file.
 * @param path - the tsconfig file.
 * @returns the parsed options, file names and project references.
 */
function parseConfig(path: string): ts.ParsedCommandLine {
  const parsed = ts.getParsedCommandLineOfConfigFile(path, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
      throw new Error(`facade: ${path}: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')}`)
    },
  })
  if (parsed === undefined) throw new Error(`facade: ${path} did not parse`)
  return parsed
}

/**
 * The tsconfig that covers a source file: the nearest `tsconfig.json` above it, or, when that is a solution file, the
 * referenced configuration whose files include the source.
 * @param file - the absolute path of the source.
 * @returns the covering tsconfig's path and parse.
 */
function configOf(file: string): { readonly path: string, readonly parsed: ts.ParsedCommandLine } {
  let directory = dirname(file)
  while (!existsSync(join(directory, 'tsconfig.json'))) {
    const parent = dirname(directory)
    if (parent === directory) throw new Error(`facade: no tsconfig.json above ${file}`)
    directory = parent
  }
  const path = join(directory, 'tsconfig.json')
  const parsed = parseConfig(path)
  if (parsed.fileNames.includes(file)) return { path, parsed }
  for (const reference of parsed.projectReferences ?? []) {
    const referenced = existsSync(join(reference.path, 'tsconfig.json')) ? join(reference.path, 'tsconfig.json') : reference.path
    const candidate = parseConfig(referenced)
    if (candidate.fileNames.includes(file)) return { path: referenced, parsed: candidate }
  }
  throw new Error(`facade: no tsconfig under ${directory} includes ${file}`)
}

/**
 * Whether a declaration is exported from its module.
 * @param declaration - the declaration.
 * @returns whether it carries `export`.
 */
function isExported(declaration: ts.Declaration): boolean {
  return (ts.getCombinedModifierFlags(declaration) & ts.ModifierFlags.Export) !== 0
}

/**
 * The first interface, class or type alias declaration of a symbol.
 * @param symbol - the symbol.
 * @returns the declaration, or `undefined` for anonymous and value symbols.
 */
function namedDeclaration(symbol: ts.Symbol | undefined): ts.Declaration | undefined {
  return symbol?.declarations?.find((declaration) => ts.isInterfaceDeclaration(declaration) || ts.isClassDeclaration(declaration) || ts.isTypeAliasDeclaration(declaration))
}

/**
 * The type arguments of an instantiated named type.
 * @param checker - the checker.
 * @param type - the type.
 * @returns the arguments in declaration order, without the implicit `this` type.
 */
function typeArgumentsOf(checker: ts.TypeChecker, type: ts.Type): readonly ts.Type[] {
  if (type.aliasSymbol !== undefined) return type.aliasTypeArguments ?? []
  if ((type.flags & ts.TypeFlags.Object) === 0 || ((type as ts.ObjectType).objectFlags & ts.ObjectFlags.Reference) === 0) return []
  const reference = type as ts.TypeReference
  return checker.getTypeArguments(reference).slice(0, reference.target.typeParameters?.length ?? 0)
}

/**
 * Whether a property is `readonly`.
 * @param property - the property symbol.
 * @returns whether the property is read-only.
 */
function isReadonly(property: ts.Symbol): boolean {
  if (((ts as TsInternals).getCheckFlags?.(property) ?? 0) & CHECK_FLAG_READONLY) return true
  return property.declarations?.some((declaration) => (ts.getCombinedModifierFlags(declaration) & ts.ModifierFlags.Readonly) !== 0) ?? false
}

/**
 * A property name as written in a type literal.
 * @param name - the property's name.
 * @returns the name, quoted unless it is an identifier.
 */
function nameOf(name: string): string {
  if (BRAND_KEY.test(name)) return '__brand'
  return /^[A-Za-z_$][\w$]*$/u.test(name) ? name : JSON.stringify(name)
}

/**
 * Print a list of types as the arguments of a generic type.
 * @param context - the printer's state.
 * @param args - the type arguments.
 * @returns `<A, B>`, or the empty string for no arguments.
 */
function printArguments(context: PrintContext, args: readonly ts.Type[]): string {
  return args.length === 0 ? '' : `<${args.map((argument) => print(context, argument)).join(', ')}>`
}

/**
 * How a named type is written, when it is not expanded.
 * @param context - the printer's state.
 * @param type - the type.
 * @returns the reference, or `undefined` to expand the type.
 */
function printNamed(context: PrintContext, type: ts.Type): string | undefined {
  const symbol = type.aliasSymbol ?? type.symbol
  const declaration = namedDeclaration(symbol)
  if (symbol === undefined || declaration === undefined) return undefined
  if (OPAQUE_TYPES.has(symbol.name)) return 'unknown'
  const file = declaration.getSourceFile().fileName
  const args = (): string => printArguments(context, typeArgumentsOf(context.checker, type))
  if (file.includes('/@types/react/')) {
    const name = context.checker.getFullyQualifiedName(symbol).replace(/^(?:"[^"]*"|React)\./u, '')
    return `import('react').${name}${args()}`
  }
  if (/\/typescript\/lib\/lib\.[^/]*\.d\.ts$/u.test(file)) return `${context.checker.getFullyQualifiedName(symbol)}${args()}`
  if (file.startsWith(`${context.root}/delorun/packages/`) && file.includes('/src/') && IMPORTABLE_FILES.test(file) && isExported(declaration)) {
    const facadeDirectory = dirname(join(context.root, FACADE_FILE))
    const path = relative(facadeDirectory, file)
    return `import('${path.startsWith('.') ? path : `./${path}`}').${symbol.name}${args()}`
  }
  return undefined
}

/**
 * Indent a multi-line text by one level.
 * @param text - the text.
 * @returns the text with two spaces before each line.
 */
function indented(text: string): string {
  return text.split('\n').map((line) => `  ${line}`).join('\n')
}

/**
 * Print a call signature as a function type or as the parameters-and-result part of a call signature member.
 * @param context - the printer's state.
 * @param signature - the signature.
 * @param separator - `=>` for a function type, `:` for a member.
 * @returns the signature's text.
 */
function printSignature(context: PrintContext, signature: ts.Signature, separator: '=>' | ':'): string {
  const { checker } = context
  const typeParameters = (signature.typeParameters ?? []).map((parameter) => {
    const constraint = checker.getBaseConstraintOfType(parameter)
    return constraint === undefined || (constraint.flags & ts.TypeFlags.Unknown) !== 0 ? parameter.symbol.name : `${parameter.symbol.name} extends ${print(context, constraint)}`
  })
  const parameters = signature.getParameters().map((parameter, index) => {
    const declaration = parameter.valueDeclaration
    const named = declaration !== undefined && ts.isParameter(declaration)
    const rest = named && declaration.dotDotDotToken !== undefined
    const optional = named && checker.isOptionalParameter(declaration)
    const name = named && ts.isIdentifier(declaration.name) ? declaration.name.text : `arg${index}`
    return `${rest ? '...' : ''}${name}${optional ? '?' : ''}: ${print(context, checker.getTypeOfSymbol(parameter))}`
  })
  const predicate = checker.getTypePredicateOfSignature(signature)
  let result = print(context, checker.getReturnTypeOfSignature(signature))
  if (predicate?.kind === ts.TypePredicateKind.Identifier) result = `${predicate.parameterName} is ${print(context, predicate.type)}`
  if (predicate?.kind === ts.TypePredicateKind.AssertsIdentifier) result = `asserts ${predicate.parameterName}${predicate.type === undefined ? '' : ` is ${print(context, predicate.type)}`}`
  return `${typeParameters.length === 0 ? '' : `<${typeParameters.join(', ')}>`}(${parameters.join(', ')})${separator === '=>' ? ' =>' : ':'} ${result}`
}

/**
 * Print an anonymous object type: a function type, or members with call signatures.
 * @param context - the printer's state.
 * @param type - the object type.
 * @returns the type's text.
 */
function printObject(context: PrintContext, type: ts.Type): string {
  const { checker } = context
  const properties = checker.getPropertiesOfType(type)
  const signatures = type.getCallSignatures()
  const indexes = checker.getIndexInfosOfType(type)
  if (properties.length === 0 && indexes.length === 0 && signatures.length === 1) return printSignature(context, signatures[0]!, '=>')
  if (type.getConstructSignatures().length > 0) context.warnings.push(`${context.component.name}: a construct signature is left out`)
  const members = [
    ...signatures.map((signature) => printSignature(context, signature, ':')),
    ...indexes.map((info) => `${info.isReadonly ? 'readonly ' : ''}[key: ${print(context, info.keyType)}]: ${print(context, info.type)}`),
    ...properties.map((property) => {
      const optional = (property.flags & ts.SymbolFlags.Optional) !== 0
      return `${isReadonly(property) ? 'readonly ' : ''}${nameOf(property.name)}${optional ? '?' : ''}: ${print(context, checker.getTypeOfSymbol(property))}`
    }),
  ]
  return members.length === 0 ? '{}' : `{\n${members.map((member) => indented(member)).join('\n')}\n}`
}

/**
 * Print the members of a union or intersection.
 * @param context - the printer's state.
 * @param type - the union or intersection.
 * @returns the type's text.
 */
function printCombination(context: PrintContext, type: ts.UnionOrIntersectionType): string {
  const union = (type.flags & ts.TypeFlags.Union) !== 0
  const texts: string[] = []
  let booleanSeen = false
  for (const member of type.types) {
    if (union && (member.flags & ts.TypeFlags.BooleanLiteral) !== 0) {
      if (!booleanSeen) texts.push('boolean')
      booleanSeen = true
      continue
    }
    const text = print(context, member)
    const function_ = /^[(<]/u.test(text)
    const text2 = function_ || (!union && (member.flags & ts.TypeFlags.Union) !== 0) ? `(${text})` : text
    if (!texts.includes(text2)) texts.push(text2)
  }
  const members = union ? texts : texts.filter((text) => texts.length === 1 || (text !== '{}' && text !== 'object'))
  return members.join(union ? ' | ' : ' & ')
}

/**
 * Print a tuple type.
 * @param context - the printer's state.
 * @param type - the tuple type reference.
 * @returns the type's text.
 */
function printTuple(context: PrintContext, type: ts.TypeReference): string {
  const target = type.target as ts.TupleType
  const elements = context.checker.getTypeArguments(type).map((element, index) => {
    const flags = target.elementFlags[index]!
    const text = print(context, element)
    if ((flags & ELEMENT_REST) !== 0 || (flags & ELEMENT_VARIADIC) !== 0) return `...${text}`
    return (flags & ELEMENT_OPTIONAL) !== 0 ? `${text}?` : text
  })
  return `${target.readonly ? 'readonly ' : ''}[${elements.join(', ')}]`
}

/**
 * Print a type as a self-contained TypeScript type expression.
 * @param context - the printer's state.
 * @param type - the type.
 * @returns the type's text.
 */
function print(context: PrintContext, type: ts.Type): string {
  const { checker } = context
  if ((type.flags & ts.TypeFlags.TypeParameter) !== 0) return type.symbol.name
  if ((type.flags & ts.TypeFlags.Boolean) !== 0) return 'boolean'
  const named = printNamed(context, type)
  if (named !== undefined) return named
  const known = context.names.get(type)
  if (known !== undefined) return known
  if (context.counting) {
    const count = context.counts.get(type) ?? 0
    context.counts.set(type, count + 1)
    if (count > 0) return 'unknown'
  }
  if (context.path.includes(type)) return nameType(context, type)
  if (context.path.length >= MAX_DEPTH) {
    throw new Error(`facade: ${context.component.name} nests ${MAX_DEPTH} types deep at ${context.checker.typeToString(type).slice(0, 80)}; add the type that starts the descent to OPAQUE_TYPES`)
  }
  const declarable = context.path.length > 0 && (type.flags & (ts.TypeFlags.Object | ts.TypeFlags.UnionOrIntersection)) !== 0
  context.path.push(type)
  try {
    const body = printBody(context, type)
    const name = context.names.get(type)
    if (name !== undefined) {
      context.lifted.set(name, body)
      return name
    }
    const lines = body.split('\n').length
    const shared = (context.counts.get(type) ?? 0) > 1 && body.length > SHARED_MIN_LENGTH
    if (context.counting || !declarable || (lines < DECLARED_MIN_LINES && !shared)) return body
    context.lifted.set(nameType(context, type), body)
    return context.names.get(type)!
  } finally {
    context.path.pop()
  }
}

/**
 * Give a type a name the facade declares it under.
 * @param context - the printer's state.
 * @param type - the type.
 * @returns the name, unique in the facade.
 */
function nameType(context: PrintContext, type: ts.Type): string {
  const base = type.aliasSymbol?.name ?? (type.symbol !== undefined && !type.symbol.name.startsWith('__') ? type.symbol.name : 'Shape')
  let name = `Replica${base}`
  for (let index = 2; context.lifted.has(name) || [...context.names.values()].includes(name); index++) name = `Replica${base}${index}`
  context.names.set(type, name)
  return name
}

/**
 * Print the structure of a type that has no name to refer to it by.
 * @param context - the printer's state.
 * @param type - the type.
 * @returns the type's text.
 */
function printBody(context: PrintContext, type: ts.Type): string {
  const { checker } = context
  if ((type.flags & ts.TypeFlags.UnionOrIntersection) !== 0) return printCombination(context, type as ts.UnionOrIntersectionType)
  if ((type.flags & ts.TypeFlags.Object) !== 0) {
    if (checker.isTupleType(type)) return printTuple(context, type as ts.TypeReference)
    return printObject(context, type)
  }
  if ((type.flags & (ts.TypeFlags.Conditional | ts.TypeFlags.Index | ts.TypeFlags.IndexedAccess | ts.TypeFlags.Substitution)) !== 0) {
    const constraint = checker.getBaseConstraintOfType(type)
    context.warnings.push(`${context.component.name}: ${checker.typeToString(type)} depends on a type parameter and is printed as ${constraint === undefined ? 'any' : 'its constraint'}`)
    if (constraint === undefined || constraint === type) return 'any'
    const text = print(context, constraint)
    return (constraint.flags & ts.TypeFlags.Union) !== 0 ? `(${text})` : text
  }
  return checker.typeToString(type, undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope)
}

/**
 * The props type of one component: the first parameter of its first call signature.
 * @param compiled - the program that contains the component.
 * @param file - the component's absolute path.
 * @param name - the component's export name.
 * @returns the props type.
 */
function propsOf(compiled: Compiled, file: string, name: string): ts.Type {
  const { checker, program } = compiled
  const source = program.getSourceFile(file)
  if (source === undefined) throw new Error(`facade: ${file} is not in its program`)
  const unresolved = program.getSemanticDiagnostics(source).filter((diagnostic) => UNRESOLVED_CODES.has(diagnostic.code))
  if (unresolved.length > 0) {
    throw new Error(`facade: ${file} has unresolved names: ${unresolved.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, ' ')).join('; ')}`)
  }
  const module = checker.getSymbolAtLocation(source)
  const symbol = module === undefined ? undefined : checker.getExportsOfModule(module).find((candidate) => candidate.name === name)
  if (symbol === undefined) throw new Error(`facade: ${file} does not export ${name}`)
  const signature = checker.getTypeOfSymbol(symbol).getCallSignatures()[0]
  const parameter = signature?.getParameters()[0]
  if (parameter === undefined) throw new Error(`facade: ${name} in ${file} is not a component with props`)
  return checker.getTypeOfSymbol(parameter)
}

/**
 * Declare the shared types once. Each program types the same source type separately, so the same body can be declared
 * under several names; the later names are replaced by the first.
 * @param lifted - the shared types' bodies, by name.
 * @param declarations - the component declarations that refer to them.
 * @returns the declaration lines: the shared types, then the components.
 */
function mergeEqualTypes(lifted: ReadonlyMap<string, string>, declarations: readonly string[]): string[] {
  let types = [...lifted]
  let components = [...declarations]
  for (;;) {
    const first = new Map<string, string>()
    const replaced = new Map<string, string>()
    for (const [name, body] of types) {
      const canonical = first.get(body)
      if (canonical === undefined) first.set(body, name)
      else replaced.set(name, canonical)
    }
    if (replaced.size === 0) break
    const rename = (text: string): string => text.replace(/\bReplica\w+\b/gu, (name) => replaced.get(name) ?? name)
    types = types.filter(([name]) => !replaced.has(name)).map(([name, body]) => [name, rename(body)])
    components = components.map(rename)
  }
  return [...types.map(([name, body]) => indented(`type ${name} = ${body}`)), ...components.map(indented)]
}

/**
 * Write the declarations of every studio component's props.
 * @param root - the repository's root, without a trailing slash.
 * @returns the text of `studio/facade.d.ts`.
 */
export function buildFacade(root: string): string {
  const counts = new Map<ts.Type, number>()
  const configs = STUDIO_COMPONENTS.map((component) => {
    const file = sourcePath(root, component.file)
    return { component, file, ...configOf(file) }
  })
  const programs = new Map<string, Compiled>()
  for (const { path, parsed } of configs) {
    if (programs.has(path)) continue
    const files = configs.filter((candidate) => candidate.path === path).map((candidate) => candidate.file)
    const program = ts.createProgram({ rootNames: [...new Set([...parsed.fileNames, ...files])], options: parsed.options })
    programs.set(path, { program, checker: program.getTypeChecker() })
  }
  const render = (counting: boolean, warnings: string[], lifted: Map<string, string>): string[] => configs.map(({ component, file, path }) => {
    const compiled = programs.get(path)!
    const context: PrintContext = { checker: compiled.checker, root, component, path: [], warnings, counting, counts, names, lifted }
    const props = print(context, propsOf(compiled, file, component.name))
    return `/** Props of ${component.file} \`${component.name}\`. */\nexport const ${component.name}: import('react').ComponentType<${props}>`
  })
  const names = new Map<ts.Type, string>()
  render(true, [], new Map())
  names.clear()
  const warnings: string[] = []
  const lifted = new Map<string, string>()
  const declarations = render(false, warnings, lifted)
  for (const warning of new Set(warnings)) process.stderr.write(`facade: ${warning}\n`)
  return `${HEADER}\ndeclare module 'virtual:replica-studio' {\n${mergeEqualTypes(lifted, declarations).join('\n')}\n}\n`
}

/**
 * Write the facade, or with `--check` compare it with the file on disk.
 * @param args - the command line's arguments.
 * @returns the process's exit code.
 */
function main(args: readonly string[]): number {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../../..')
  const target = join(root, FACADE_FILE)
  const text = buildFacade(root)
  if (args.includes('--check')) {
    if (existsSync(target) && readFileSync(target, 'utf8') === text) return 0
    process.stderr.write(`facade: ${FACADE_FILE} is out of date; run node_modules/.bin/tsx delorun/apps/website/src/replica/build/facade.ts\n`)
    return 1
  }
  writeFileSync(target, text)
  return 0
}


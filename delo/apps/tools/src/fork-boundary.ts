/**
 * The divergence ledger's rules. Every difference between the repository and its pinned upstream commit lies under a
 * fork-owned entry, is listed under `patches` with a class and a reason, is covered by a path rule under `rules`, or is
 * recorded under `retired` because upstream absorbed the change. Upstream source files need a listed entry; a path rule
 * covers only paths that are not upstream source, except an exact `generated` rule.
 *
 * @module @delo/tools/fork-boundary
 */
import { posix } from 'node:path'
import { z } from 'zod'

/** The ledger's path, relative to the repository root. */
export const MANIFEST_PATH = 'delo/upstream-patches.json'

/** The value a stub entry carries in `feature` and `reason` until the lead writes them; the entry rules refuse it. */
export const TODO_VALUE = 'TODO'

/** The kinds a path rule names: what the paths it covers are. */
export const RULE_KINDS = ['tests', 'recorded-sessions', 'translations', 'documentation', 'tooling', 'generated'] as const

/** The text a generated file holds within its first {@link GENERATED_HEAD_LINES} lines. */
export const GENERATED_MARKER = 'Generated by scripts/'

/** The number of leading lines in which a generated file names its generator. */
export const GENERATED_HEAD_LINES = 5

const commitId = z.string().regex(/^[0-9a-f]{40}$/u, { error: 'must be a full 40-character lowercase commit id' })

const sha256Hex = (subject: string): z.ZodString => z.string().regex(/^[0-9a-f]{64}$/u, { error: `must be the SHA-256 digest of ${subject}, in lowercase hexadecimal` })

/** One line of text that holds a non-space character: the form of a non-model-visible hunk record's `reason`. */
export const ONE_LINE_REASON = /^[^\r\n]*\S[^\r\n]*$/u

/**
 * Report whether a string is a path inside the repository: not absolute, no `..` segment and no control character.
 * @param path - the candidate path or pattern.
 * @returns true when the string stays inside the repository.
 */
function insideRepository(path: string): boolean {
  return !path.startsWith('/') && !path.split('/').includes('..') && !/\p{Cc}/u.test(path)
}

/**
 * A path inside the repository. An entry names a file the update path reads with `git cat-file`, writes into a scratch
 * worktree and digests, so a path that is absolute, that climbs out of the repository with a `..` segment, or that
 * carries a control character is refused: the object store's batch protocol cannot read such a path back, and the
 * digest it answers for would be another file's.
 */
const repoPath = z.string().min(1).refine(
  insideRepository,
  { error: 'must be a repository-relative path: no leading `/`, no `..` segment and no control character' },
)

const manifestSchema = z.strictObject({
  $schema: z.string().optional(),
  upstream: z.strictObject({
    repository: z.string().min(1),
    ref: z.string().min(1),
    commit: commitId,
  }),
  forkOwned: z.array(z.string().min(1)).min(1),
  rules: z.array(z.strictObject({
    pattern: z.string().min(1).refine(
      pattern => insideRepository(pattern) && !pattern.startsWith('!'),
      { error: 'must be a repository-relative glob: no leading `/` or `!`, no `..` segment and no control character' },
    ),
    kind: z.enum(RULE_KINDS),
    reason: z.string(),
  })).default([]),
  patches: z.array(z.strictObject({
    path: repoPath,
    class: z.enum(['delo-feature', 'generic-fix', 'security']),
    feature: z.string().optional(),
    reason: z.string(),
    sha256: sha256Hex('the file').optional(),
    nonModelVisibleHunks: z.array(z.strictObject({
      sha256: sha256Hex('a hunk of the file\'s zero-context diff'),
      reason: z.string().regex(ONE_LINE_REASON, { error: 'must be one line that holds a non-space character' }),
    })).min(1).optional(),
  })),
  retired: z.array(z.strictObject({
    path: repoPath,
    reason: z.literal('absorbed'),
    upstreamCommit: commitId,
    hunks: z.number().int().nonnegative(),
  })),
})

/** The ledger stored at {@link MANIFEST_PATH}. */
export type PatchManifest = z.infer<typeof manifestSchema>

/**
 * One listed patch: an upstream path the fork edits, with its class and reason. A `security` entry records the
 * `sha256` of its file and names no feature; any other entry names the `feature` it serves and records no digest. Only
 * a `security` entry may hold `nonModelVisibleHunks`, which `ledger-record.ts --non-model-visible-hunk` writes.
 */
export type Patch = PatchManifest['patches'][number]

/**
 * One hunk of a security entry's zero-context diff against the pinned commit that the lead reviewed as not
 * model-visible although it touches a top-level statement that registers a model-visible contribution: the hunk's
 * digest, as `DiffHunk.sha256` in `parity/composition/contributions.ts` defines it, and why the model sees no
 * difference. `parity-switches` passes one hunk with that digest per record.
 */
export type NonModelVisibleHunk = NonNullable<Patch['nonModelVisibleHunks']>[number]

/** One path rule: a glob over repository-relative paths, the kind of path it covers, and why the fork changes them. */
export type PathRule = PatchManifest['rules'][number]

/** One retired entry: an upstream path whose change upstream absorbed, with the absorbing commit and its hunk count. */
export type RetiredEntry = PatchManifest['retired'][number]

/**
 * Parse and validate the ledger's text. Malformed JSON and schema violations both throw and name the
 * ledger and the failing fields; {@link manifestErrors} checks what the entries say.
 * @param text - the JSON text of the ledger.
 * @returns the typed ledger, with `rules` empty when the text has none.
 * @throws Error when the text is not JSON or does not match the ledger schema.
 */
export function parseManifest(text: string): PatchManifest {
  let value: unknown
  try {
    value = JSON.parse(text)
  } catch (error) {
    throw new Error(`${MANIFEST_PATH}: not valid JSON: ${error instanceof Error ? error.message : String(error)}`)
  }
  const parsed = manifestSchema.safeParse(value)
  if (parsed.success) return parsed.data
  throw new Error(`${MANIFEST_PATH}: ${parsed.error.issues.map(issue => `${issue.path.map(String).join('.')}: ${issue.message}`).join('; ')}`)
}

/** One path that differs from the upstream commit. */
export interface ChangedPath {
  /** Repository-relative path with `/` separators. */
  readonly path: string
  /** How the path differs from the upstream commit. */
  readonly status: 'added' | 'modified' | 'deleted'
}

const COMPILED_SUFFIXES = ['.d.ts.map', '.js.map', '.d.ts', '.js'] as const
const SOURCE_SUFFIXES = ['.ts', '.tsx', '.mts'] as const

/** The trees that hold upstream source, before the exclusions of {@link isUpstreamSource} apply. */
const SOURCE_TREES: readonly RegExp[] = [
  /^packages\/(?:[^/]+\/)*src\//u,
  /^apps\/(?:[^/]+\/)*src\//u,
  /^native\//u,
  /^python\/.*\.py$/u,
  /^scripts\/(?!tests\/)(?:[^/]+\/)*[^/]+\.(?:ts|mjs)$/u,
]

/** Paths inside a source tree that are not source: specs, test trees, fixtures, recorded sessions, Markdown and consistency records. */
const NOT_SOURCE: readonly RegExp[] = [
  /\.(?:spec|test)\.[^/]+$/u,
  /(?:^|\/)(?:tests|__tests__|fixtures|snapshots)\//u,
  /\.md$/u,
  /\.i18n\.yaml$/u,
]

/**
 * Report whether a path is upstream source, which only a listed entry may cover. Every path under `vendor/` is source;
 * otherwise a path is source when it lies under a `src/` directory of `packages/` or `apps/`, under `native/`, is a
 * Python file under `python/`, or is a `.ts` or `.mjs` file under `scripts/` outside `scripts/tests/`, and is not a
 * spec or test file, not under a `tests/`, `__tests__/`, `fixtures/` or `snapshots/` directory, not Markdown and not
 * a `.i18n.yaml` consistency record. A generated source file is still source by this test; only an exact `generated`
 * rule may cover it.
 * @param path - repository-relative path with `/` separators.
 * @returns true when the path is upstream source.
 */
export function isUpstreamSource(path: string): boolean {
  if (path.startsWith('vendor/')) return true
  return SOURCE_TREES.some(tree => tree.test(path)) && !isExcludedFromSource(path)
}

/**
 * Report whether a path is a spec or test file, lies in a test, fixture or recorded-session tree, is Markdown or is a
 * consistency record: the exclusions {@link isUpstreamSource} applies inside the source trees.
 * @param path - repository-relative path with `/` separators.
 * @returns true when one exclusion applies.
 */
function isExcludedFromSource(path: string): boolean {
  return NOT_SOURCE.some(exclusion => exclusion.test(path))
}

/**
 * Report whether a fork-owned entry covers a path. An entry is a path or a glob: `*` matches within one
 * path segment and `**` across segments. An entry covers the path it matches and every path below a
 * matching directory, so `delo/` covers everything under `delo/` and a trailing `/` is optional.
 * @param path - repository-relative path with `/` separators.
 * @param forkOwned - the ledger's fork-owned entries.
 * @returns true when one entry covers the path.
 */
export function isForkOwned(path: string, forkOwned: readonly string[]): boolean {
  return forkOwned.some(entry => forkOwnedPattern(entry).test(path))
}

/**
 * Compile one fork-owned entry into a pattern anchored at the start of a path and ending at a segment boundary.
 * @param entry - a fork-owned entry, with an optional trailing `/`.
 * @returns the compiled pattern.
 */
function forkOwnedPattern(entry: string): RegExp {
  const glob = entry.endsWith('/') ? entry.slice(0, -1) : entry
  const source = glob.replace(/\*\*\/|\*\*|\*|[.+?^${}()|[\]\\]/gu, token => {
    if (token === '**/') return '(?:.*/)?'
    if (token === '**') return '.*'
    if (token === '*') return '[^/]*'
    return `\\${token}`
  })
  return new RegExp(`^${source}(?:/|$)`, 'u')
}

/**
 * Report whether a rule's pattern matches a path: the whole path, case-sensitively, with `path.posix.matchesGlob`.
 * `*` matches within one segment, `**` across segments, and neither matches a segment that starts with `.`.
 * @param path - repository-relative path with `/` separators.
 * @param pattern - the rule's glob.
 * @returns true when the pattern matches the whole path.
 */
export function ruleMatches(path: string, pattern: string): boolean {
  return posix.matchesGlob(path, pattern)
}

/**
 * Report whether a pattern names one path exactly, without glob syntax.
 * @param pattern - the rule's glob.
 * @returns true when the pattern has no glob metacharacter.
 */
function isExactPattern(pattern: string): boolean {
  return !/[*?[\]{}()!+@]/u.test(pattern)
}

/**
 * Report whether a rule may cover a path it matches: any path that is not upstream source, and, for a `generated` rule
 * whose pattern names the path exactly, a source path outside `vendor/`.
 * @param rule - the path rule.
 * @param path - a path the rule's pattern matches.
 * @returns true when the rule covers the path.
 */
function mayCover(rule: PathRule, path: string): boolean {
  if (!isUpstreamSource(path)) return true
  return rule.kind === 'generated' && isExactPattern(rule.pattern) && !path.startsWith('vendor/')
}

/**
 * The rules that cover a path: each rule whose pattern matches it and that may cover it.
 * @param path - repository-relative path with `/` separators.
 * @param rules - the ledger's path rules.
 * @returns the covering rules, in ledger order; empty when none covers the path.
 */
export function coveringRules(path: string, rules: readonly PathRule[]): PathRule[] {
  return rules.filter(rule => ruleMatches(path, rule.pattern) && mayCover(rule, path))
}

/**
 * Source paths every rule is held to, beside the paths of the tree a caller passes, so that a rule broad enough to
 * reach source is refused even where no tree is at hand.
 */
const SOURCE_PROBES: readonly string[] = [
  'packages/group/package/src/index.ts',
  'packages/group/package/src/view.tsx',
  'apps/app/src/main.ts',
  'native/src/lib.rs',
  'vendor/package/src/index.ts',
  'python/package/module.py',
  'scripts/script.ts',
  'scripts/script.mjs',
]

/**
 * Find the differing upstream source files that an exact `generated` rule covers.
 * @param manifest - the parsed ledger.
 * @param changed - paths that differ from the upstream commit.
 * @returns the differing source paths that only an exact `generated` rule covers; each must hold {@link GENERATED_MARKER}.
 */
export function generatedSources(manifest: PatchManifest, changed: readonly ChangedPath[]): string[] {
  const listed = new Set(manifest.patches.map(patch => patch.path))
  return changed
    .filter(entry => !listed.has(entry.path) && !isForkOwned(entry.path, manifest.forkOwned) && isUpstreamSource(entry.path))
    .filter(entry => coveringRules(entry.path, manifest.rules).length > 0)
    .map(entry => entry.path)
}

/**
 * Report whether a file's text names its generator within its first lines.
 * @param text - the file's text.
 * @returns true when one of its first {@link GENERATED_HEAD_LINES} lines holds {@link GENERATED_MARKER}.
 */
export function isGeneratedText(text: string): boolean {
  return text.split('\n').slice(0, GENERATED_HEAD_LINES).some(line => line.includes(GENERATED_MARKER))
}

/**
 * Report whether a feature name is a kebab-case identifier.
 * @param feature - the entry's `feature`.
 * @returns true when the value is lowercase words and digits joined by single hyphens.
 */
function isFeatureId(feature: string): boolean {
  return /^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(feature)
}

/**
 * Validate what the ledger's entries and rules say: reasons, duplicates, entries that claim fork-owned paths, the digest,
 * feature and non-model-visible hunks each class requires or forbids, placeholder values, and rules that would cover
 * upstream source.
 * @param manifest - the parsed ledger.
 * @param paths - the repository's paths, against which each rule is held so that it covers no source; the built-in
 * source probes are always added.
 * @returns one message per defect; empty when the entries and rules are well formed.
 */
export function manifestErrors(manifest: PatchManifest, paths: Iterable<string> = []): string[] {
  const errors: string[] = []
  const seen = new Set<string>()
  for (const { path } of [...manifest.patches, ...manifest.retired]) {
    if (seen.has(path)) errors.push(`${path}: listed more than once`)
    seen.add(path)
  }
  for (const patch of manifest.patches) errors.push(...patchErrors(patch))
  for (const { path } of [...manifest.patches, ...manifest.retired]) {
    if (isForkOwned(path, manifest.forkOwned)) errors.push(`${path}: fork-owned paths are not ledger entries; remove the entry`)
  }
  errors.push(...ruleErrors(manifest, paths))
  return errors
}

/**
 * Validate one listed patch: its reason, and the digest, feature and non-model-visible hunks its class requires or
 * forbids.
 * @param patch - the listed patch.
 * @returns one message per defect.
 */
function patchErrors(patch: Patch): string[] {
  const errors: string[] = []
  const { path } = patch
  if (patch.reason.trim().length === 0) errors.push(`${path}: a patch needs a reason`)
  if (patch.reason.trim() === TODO_VALUE) errors.push(`${path}: the reason is ${TODO_VALUE}; the lead writes the reason`)
  if (patch.class === 'security') {
    if (patch.sha256 === undefined) errors.push(`${path}: a security entry records the sha256 of its file; run \`ledger-record.ts\` after the lead's review`)
    if (patch.feature !== undefined) errors.push(`${path}: a security entry names no feature; remove \`feature\``)
    return errors
  }
  if (patch.sha256 !== undefined) errors.push(`${path}: only a security entry records a sha256; remove it from this ${patch.class} entry`)
  if (patch.nonModelVisibleHunks !== undefined) {
    errors.push(`${path}: only a security entry records \`nonModelVisibleHunks\`; remove them from this ${patch.class} entry`)
  }
  if (patch.feature === undefined) {
    errors.push(`${path}: a ${patch.class} entry names the feature it serves in \`feature\``)
  } else if (patch.feature === TODO_VALUE) {
    errors.push(`${path}: the feature is ${TODO_VALUE}; the lead names the feature this entry serves`)
  } else if (!isFeatureId(patch.feature)) {
    errors.push(`${path}: feature ${JSON.stringify(patch.feature)} is not a kebab-case identifier`)
  }
  return errors
}

/**
 * Validate the path rules: duplicates, reasons, the bare `**`, rules that match upstream source they may not cover, and
 * non-security entries that a rule also covers. A `security` entry stays an entry whatever rule matches its path. A
 * `vendor/` path that is a spec, lies in a test, fixture or recorded-session tree, or is Markdown or a consistency
 * record is not held against the rules: no rule covers a `vendor/` path, so matching one swallows nothing.
 * @param manifest - the parsed ledger.
 * @param paths - the repository's paths, held against each rule beside the built-in source probes.
 * @returns one message per defect.
 */
function ruleErrors(manifest: PatchManifest, paths: Iterable<string>): string[] {
  const errors: string[] = []
  const seen = new Set<string>()
  const sources = [...new Set([...SOURCE_PROBES, ...paths])].filter(isUpstreamSource)
  for (const rule of manifest.rules) {
    const { pattern } = rule
    if (seen.has(pattern)) errors.push(`rule ${pattern}: listed more than once`)
    seen.add(pattern)
    if (rule.reason.trim().length === 0 || rule.reason.trim() === TODO_VALUE) errors.push(`rule ${pattern}: a rule needs a reason`)
    if (pattern === '**') {
      errors.push(`rule ${pattern}: a bare \`**\` covers every path; name the paths the rule covers`)
      continue
    }
    const source = sources.find(path => ruleMatches(path, pattern) && !mayCover(rule, path) && !(path.startsWith('vendor/') && isExcludedFromSource(path)))
    if (source !== undefined) errors.push(`rule ${pattern}: matches upstream source such as ${source}; source paths need a listed entry`)
  }
  for (const patch of manifest.patches) {
    if (patch.class === 'security') continue
    const [rule] = coveringRules(patch.path, manifest.rules)
    if (rule !== undefined) errors.push(`${patch.path}: listed and ruled by ${rule.pattern}; remove the entry or narrow the rule`)
  }
  return errors
}

/**
 * Check every difference from upstream against the ledger. A differing path that is not fork-owned passes when an
 * entry lists it, or when a rule covers it: a path that is not upstream source, or a source path that an exact
 * `generated` rule names.
 * @param manifest - the parsed ledger.
 * @param changed - paths that differ from the upstream commit, including uncommitted edits to tracked files.
 * @param files - every path present in the working tree, used to find compiled twins and to hold each rule to.
 * @returns one message per violation; empty when the fork boundary holds.
 */
export function forkBoundaryErrors(manifest: PatchManifest, changed: readonly ChangedPath[], files: ReadonlySet<string>): string[] {
  const errors = manifestErrors(manifest, [...files, ...changed.map(entry => entry.path)])
  const listed = new Set(manifest.patches.map(patch => patch.path))
  const retired = new Set(manifest.retired.map(entry => entry.path))
  const changedPaths = new Set(changed.map(entry => entry.path))
  for (const entry of changed) {
    if (isForkOwned(entry.path, manifest.forkOwned)) {
      const source = entry.status === 'deleted' ? undefined : compiledTwinSource(entry.path, files)
      if (source !== undefined) errors.push(`${entry.path}: compiled output beside ${source}; delete it and keep build output out of source trees`)
      continue
    }
    if (listed.has(entry.path)) continue
    if (retired.has(entry.path)) {
      errors.push(`${entry.path}: retired as absorbed upstream but still differs from it; list it under patches`)
      continue
    }
    if (coveringRules(entry.path, manifest.rules).length > 0) continue
    errors.push(isUpstreamSource(entry.path)
      ? `${entry.path}: ${entry.status} upstream source file is not listed in ${MANIFEST_PATH}; source needs an entry`
      : `${entry.path}: ${entry.status} upstream file is not listed in ${MANIFEST_PATH} and no path rule covers it`)
  }
  for (const patch of manifest.patches) {
    if (!changedPaths.has(patch.path)) errors.push(`${patch.path}: listed patch no longer differs from upstream; remove the entry`)
  }
  return errors
}

/**
 * Count the differing paths each rule covers. A path that two rules cover counts for both; a listed, retired or
 * fork-owned path counts for none.
 * @param manifest - the parsed ledger.
 * @param changed - paths that differ from the upstream commit.
 * @returns the number of covered paths per rule pattern, in ledger order; a rule that covers none maps to 0.
 */
export function ruleCoverage(manifest: PatchManifest, changed: readonly ChangedPath[]): Map<string, number> {
  const coverage = new Map(manifest.rules.map((rule): [string, number] => [rule.pattern, 0]))
  for (const path of ruledPaths(manifest, changed)) {
    for (const rule of coveringRules(path, manifest.rules)) coverage.set(rule.pattern, (coverage.get(rule.pattern) ?? 0) + 1)
  }
  return coverage
}

/**
 * The differing paths that a rule covers and no entry lists.
 * @param manifest - the parsed ledger.
 * @param changed - paths that differ from the upstream commit.
 * @returns the covered paths, in the order of `changed`.
 */
export function ruledPaths(manifest: PatchManifest, changed: readonly ChangedPath[]): string[] {
  const entries = new Set([...manifest.patches, ...manifest.retired].map(entry => entry.path))
  return changed
    .map(entry => entry.path)
    .filter(path => !entries.has(path) && !isForkOwned(path, manifest.forkOwned) && coveringRules(path, manifest.rules).length > 0)
}

/**
 * Find the TypeScript source a compiled file was emitted from, if one exists beside it.
 * @param path - a changed fork-owned path.
 * @param files - every path present in the working tree.
 * @returns the sibling source path, or undefined when the path is not a compiled twin.
 */
export function compiledTwinSource(path: string, files: ReadonlySet<string>): string | undefined {
  const suffix = COMPILED_SUFFIXES.find(candidate => path.endsWith(candidate))
  if (suffix === undefined) return undefined
  const stem = path.slice(0, -suffix.length)
  return SOURCE_SUFFIXES.map(source => stem + source).find(source => files.has(source))
}

/** The divergence from the pinned upstream commit: the listed patches and the rule-covered paths measured in hunks, and the retired entries credited. */
export interface Divergence {
  /** Listed patches that differ from the pinned commit. */
  readonly entries: number
  /** Hunks of the listed patches, measured against the pinned commit. */
  readonly hunks: number
  /** Differing paths that a rule covers, and their hunks. */
  readonly ruled: { readonly paths: number; readonly hunks: number }
  /** Retired entries. They are not counted in `entries` or `hunks`; they are credited and listed separately. */
  readonly retired: readonly RetiredEntry[]
}

/**
 * Total the divergence of a ledger. A listed patch counts when its path appears in `hunks`, so a stale entry
 * contributes nothing; retiring an entry removes its entry and hunks from the total.
 * @param manifest - the parsed ledger.
 * @param hunks - the hunk count of every changed path, measured against the pinned commit.
 * @param ruled - the differing paths that a rule covers.
 * @returns the listed totals, the rule-covered totals and the credited retired entries.
 */
export function divergence(manifest: PatchManifest, hunks: ReadonlyMap<string, number>, ruled: readonly string[]): Divergence {
  const live = manifest.patches.filter(patch => hunks.has(patch.path))
  return {
    entries: live.length,
    hunks: live.reduce((total, patch) => total + (hunks.get(patch.path) ?? 0), 0),
    ruled: { paths: ruled.length, hunks: ruled.reduce((total, path) => total + (hunks.get(path) ?? 0), 0) },
    retired: manifest.retired,
  }
}
